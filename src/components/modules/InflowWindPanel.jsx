export default function InflowWindPanel({
  onLog, project,
  filePathFromProject, reloadKey, onDirtyChange, onRegisterSave,
  onWindParamsChange,
  simRunning = false,
}) {
  const [p,             _setP]          = useState(DEFAULT);
  const [filePath,      setFilePath]    = useState("");
  const [isDirtyFlag,   setIsDirtyFlag] = useState(false);
  const [btsFiles,      setBtsFiles]    = useState([]);
  const [scanning,      setScanning]    = useState(false);
  const [showRaw,       setShowRaw]     = useState(false);
  const [rawContent,    setRawContent]  = useState("");
  const [generating,    setGenerating]  = useState(false);
  const [customDatName, setCustomDatName] = useState("");

  // Ref holds JSON snapshot of last saved/loaded state — written synchronously
  // to avoid React batching race between setP and the snapshot update.
  const originalRef = useRef(null);

  // Ref holds the raw file text of the currently loaded file.
  // handleSave uses patchInflowWindContent() on this to update only the known
  // keys while leaving every other line (LIDAR, HAWC2, Bladed…) untouched.
  // handleGenerate stores the freshly created template here so subsequent saves
  // also use the patch strategy from that point on.
  const originalContentRef = useRef("");

  // Wrapped setP — marks panel dirty on every user-driven change
  const setP = useCallback((updater) => {
    _setP(updater);
    setIsDirtyFlag(true);
  }, []);

  // isDirty: file open + user touched something + state diverged from snapshot
  const isDirty = !!filePath && isDirtyFlag &&
    originalRef.current !== null && JSON.stringify(p) !== originalRef.current;

  // Revert detection: clear dirty flag if user undid all their changes
  useEffect(() => {
    if (!isDirtyFlag || originalRef.current === null) return;
    if (JSON.stringify(p) === originalRef.current) setIsDirtyFlag(false);
  }, [p, isDirtyFlag]); // eslint-disable-line react-hooks/exhaustive-deps

  const set    = key => e => setP(prev => ({ ...prev, [key]: e.target.value }));
  // Numbers must be stored as Number (not string) so JSON.stringify comparison
  // works correctly for the revert-detection / isDirty logic.
  const setNum = key => e => setP(prev => ({ ...prev, [key]: Number(e.target.value) }));

  const autoName         = useMemo(() => autoFilename(p.WindType, p), [p.WindType, p.HWindSpeed, p.FileName_BTS, p.Filename_Uni]); // eslint-disable-line react-hooks/exhaustive-deps
  const effectiveDatName = customDatName.trim() || autoName;

  // ── File operations ────────────────────────────────────────────────────────

  const loadFile = async (path) => {
    try {
      const content  = await invoke("read_text_file", { path });
      const kv       = parseInflowWindFile(content);
      const newState = parsedToState(kv);
      originalContentRef.current = content;          // raw text for patch writes
      originalRef.current = JSON.stringify(newState); // JSON snapshot for dirty detection
      _setP(newState);
      setIsDirtyFlag(false);
      onLog?.("ok", `Loaded ${path.split("/").pop()}`);
    } catch {
      // File is missing — auto-generate it from defaults so that subsequent
      // patchInputFileKey calls from the OpenFAST run card have a valid file
      // to read-and-patch (on Windows the file often doesn't exist until it is
      // explicitly saved, which caused the one-way sync problem).
      const fallback = { ...DEFAULT };
      const content  = buildInflowWindContent(fallback);
      try {
        await invoke("write_text_file", { path, content });
        originalContentRef.current = content;
        originalRef.current = JSON.stringify(fallback);
        _setP(fallback);
        onLog?.("info", `${path.split("/").pop()} not found — created with defaults`);
      } catch {
        // Model directory may not exist yet (project not fully configured) — stay silent
      }
    }
  };

  const handleOpen = async () => {
    try {
      const f = await openDialog({
        multiple: false, directory: false,
        filters: [{ name: "InflowWind input", extensions: ["dat"] }],
      });
      if (!f) return;
      setFilePath(f);
      await loadFile(f);
    } catch {}
  };

  const handleSave = useCallback(async () => {
    if (simRunning) {
      onLog?.("warn", "⚠ OpenFAST is running — save blocked to protect the active simulation. Wait for it to finish.");
      return;
    }
    if (!filePath) {
      onLog?.("warn", "No file open — use Open .dat or Generate first.");
      return;
    }
    // Patch strategy: only the UI-known values change; every other line
    // (LIDAR section, HAWC2 section, Bladed section, custom comments…)
    // is left exactly as it was in the file we originally read.
    const content = originalContentRef.current
      ? patchInflowWindContent(originalContentRef.current, p)
      : buildInflowWindContent(p); // fallback for programmatically set paths
    try {
      await invoke("write_text_file", { path: filePath, content });
      originalContentRef.current = content;          // patch from the saved version next time
      originalRef.current = JSON.stringify(p);       // advance dirty snapshot
      setIsDirtyFlag(false);
      onLog?.("ok", `Saved ${filePath.split("/").pop()}`);
    } catch (err) {
      onLog?.("error", `Save failed: ${String(err)}`);
    }
  }, [filePath, p]); // eslint-disable-line react-hooks/exhaustive-deps

  // Generate a new file in the project dir, then treat it as the loaded file
  const handleGenerate = async () => {
    if (!project) { onLog?.("warn", "Open a project directory first."); return; }
    if (p.WindType === 3 && !p.FileName_BTS.trim()) { onLog?.("warn", "Select a .bts file first."); return; }
    setGenerating(true);
    const outPath = `${project.modelDir ?? project.workingDir}/${effectiveDatName}`;
    const content = buildInflowWindContent(p);
    try {
      await invoke("write_text_file", { path: outPath, content });
      // Treat the generated file as the "open" file — store raw content so
      // subsequent saves use the patch strategy (preserving any future manual edits
      // to the file outside this app).
      originalContentRef.current = content;
      originalRef.current = JSON.stringify(p);
      setFilePath(outPath);
      setIsDirtyFlag(false);
      onLog?.("ok", `Generated → ${outPath}`);
    } catch (err) {
      onLog?.("error", `Write failed: ${err.message ?? err}`);
    }
    setGenerating(false);
  };

  const handleViewRaw = async () => {
    if (!filePath) {
      onLog?.("warn", "Load or save the InflowWind file first — then View will show the actual file on disk.");
      return;
    }
    try {
      const content = await invoke("read_text_file", { path: filePath });
      setRawContent(content);
      setShowRaw(true);
    } catch (err) {
      onLog?.("error", `Cannot read file: ${err}`);
    }
  };

  // Cmd+S / Ctrl+S to save
  useEffect(() => {
    const handler = (e) => {
      if ((e.metaKey || e.ctrlKey) && e.key === "s") { e.preventDefault(); handleSave(); }
    };
    window.addEventListener("keydown", handler);
    return () => window.removeEventListener("keydown", handler);
  }, [handleSave]);

  // ── Project integration effects ────────────────────────────────────────────
  useEffect(() => {
    if (!filePathFromProject) return;
    setFilePath(filePathFromProject);
    loadFile(filePathFromProject);
  }, [filePathFromProject]); // eslint-disable-line react-hooks/exhaustive-deps

  // Reload from disk when OpenFASTPanel patches the inflowwind file externally
  useEffect(() => {
    if (!reloadKey || !filePathFromProject) return;
    loadFile(filePathFromProject);
  }, [reloadKey]); // eslint-disable-line react-hooks/exhaustive-deps

  useEffect(() => { onDirtyChange?.(isDirty); }, [isDirty]); // eslint-disable-line react-hooks/exhaustive-deps
  useEffect(() => { onRegisterSave?.(handleSave); }, [handleSave]); // eslint-disable-line react-hooks/exhaustive-deps

  // Broadcast live wind params to the OpenFAST run panel whenever the user
  // changes WindType, wind speed, or BTS file — no save required.
  useEffect(() => {
    if (!filePath || !onWindParamsChange) return;
    const btsBasename = p.FileName_BTS
      ? p.FileName_BTS.replace(/\\/g, "/").split("/").pop()
      : "";
    onWindParamsChange(p.WindType, String(p.HWindSpeed), btsBasename);
  }, [p.WindType, p.HWindSpeed, p.FileName_BTS]); // eslint-disable-line react-hooks/exhaustive-deps

  // ── BTS scanning ───────────────────────────────────────────────────────────
  const scanBts = useCallback(async () => {
    if (!project) return;
    setScanning(true);
    try {
      const raw = await invoke("sidecar_call", {
        payload: JSON.stringify({ cmd: "list_bts_files", working_dir: project.windDir ?? project.workingDir }),
      });
      const res = JSON.parse(raw);
      if (res.ok) setBtsFiles(res.files);
    } catch {}
    setScanning(false);
  }, [project]);

  useEffect(() => { if (project) scanBts(); }, [project, scanBts]);

  const browseBts = async () => {
    try {
      const f = await openDialog({ multiple: false, filters: [{ name: "TurbSim wind field", extensions: ["bts"] }] });
      if (f) setP(prev => ({ ...prev, FileName_BTS: f }));
    } catch {}
  };

  const browseWnd = async () => {
    try {
      const f = await openDialog({ multiple: false, filters: [{ name: "Uniform wind file", extensions: ["wnd"] }] });
      if (f) setP(prev => ({ ...prev, Filename_Uni: f }));
    } catch {}
  };

  // ── Derived display values ─────────────────────────────────────────────────
  const Lbl = ({ children, k }) => (
    <span style={{ display: "flex", alignItems: "center", gap: 4 }}>
      {children}
      <InfoPopover content={INFO[k]} accentColor={ACCENT} />
    </span>
  );

  const wt = WIND_TYPES.find(t => t.value === p.WindType);

  const displayPath = filePath
    ? filePath.replace(/\\/g, "/").split("/").slice(-3).join("/")
    : "";

  // Sidebar stats — always show Type + Hub Ht; add wind-type-specific cards
  const stats = [
    { k: "Type",       v: wt?.label || "—" },
    { k: "Hub height", v: `${p.WindVziList} m` },
    ...(p.WindType === 1 ? [
      { k: "Wind speed", v: `${Number(p.HWindSpeed).toFixed(1)} m/s` },
      { k: "Ref height", v: `${p.RefHt} m` },
      { k: "Shear α",    v: String(p.PLexp) },
      { k: "Prop. dir",  v: `${p.PropagationDir}°` },
    ] : p.WindType === 2 ? [
      { k: "Ref height", v: `${p.RefHt_Uni} m` },
      { k: "Ref length", v: `${p.RefLength} m` },
      { k: "Prop. dir",  v: `${p.PropagationDir}°` },
      { k: "Upflow",     v: `${p.VFlowAng}°` },
    ] : [
      { k: "Prop. dir",  v: `${p.PropagationDir}°` },
      { k: "Upflow",     v: `${p.VFlowAng}°` },
    ]),
  ];

  // ── Render ─────────────────────────────────────────────────────────────────
  return (
    <div className={s.panel}>

      {/* ── Header ────────────────────────────────────────────────────────── */}
      <div className={s.header}>
        <Cloud size={14} strokeWidth={1.8} className={s.headerIcon} />
        <span className={s.title}>InflowWind</span>
        <span className={s.subtitle}>inflow conditions</span>
        <span className={s.badge}>v3.01</span>
        <div style={{ flex: 1 }} />
        <button className={`${s.headerBtn} ${s.headerBtnPrimary}`} onClick={handleOpen} type="button">
          <FolderOpen size={12} strokeWidth={1.8} /> Open .dat
        </button>
        <button className={s.eyeBtn} onClick={handleViewRaw} title="Preview .dat content" type="button">
          <Eye size={12} strokeWidth={1.8} />
          View .dat
        </button>
      </div>

      {/* ── File bar — always visible, Save lives here ────────────────────── */}
      <div className={[s.fileBar, filePath ? s.fileBarLoaded : ""].join(" ")}>
        <span className={`${s.filePath} ${filePath ? s.filePathSet : ""}`}>
          {filePath
            ? (displayPath || filePath.split("/").pop())
            : "No file open — click Open .dat to load an existing file"}
        </span>
        <span className={s.dirtyDot} style={{ opacity: isDirty ? 1 : 0 }} title="Unsaved changes" />
        <button
          className={[s.saveBtn, (!isDirty || simRunning) ? s.saveBtnInactive : ""].join(" ")}
          onClick={(!isDirty || simRunning) ? undefined : handleSave}
          type="button"
          title={simRunning ? "OpenFAST is running — save blocked" : "Save (⌘S)"}
        >
          <Save size={11} strokeWidth={2} /> Save
        </button>
      </div>

      {/* ── Simulation running banner ──────────────────────────────────────── */}
      {simRunning && (
        <div style={{
          display: "flex", alignItems: "center", gap: 8,
          padding: "7px 18px",
          background: "rgba(217,119,6,0.10)",
          borderBottom: "0.5px solid rgba(217,119,6,0.28)",
          flexShrink: 0,
        }}>
          <span style={{ fontSize: 13 }}>⚠</span>
          <span style={{ fontSize: 12, fontWeight: 500, color: "#92400E" }}>
            OpenFAST is running — saving is disabled to protect the active simulation
          </span>
        </div>
      )}

      {/* ── Raw file modal ─────────────────────────────────────────────────── */}
      {showRaw && rawContent && (
        <RawFileModal
          content={rawContent}
          filename={filePath ? filePath.split("/").pop() : "InflowWind.dat"}
          fromDisk={!!filePath}
          hasDirtyWarning={isDirty}
          onClose={() => setShowRaw(false)}
        />
      )}

      {/* ── Content row ───────────────────────────────────────────────────── */}
      <div className={s.contentRow}>

        {/* Form area */}
        <div className={s.scroll}>
          <div className={s.form}>

            {/* Wind Source */}
            <p className={s.sectionHead}>
              Wind Source
              <InfoPopover content={INFO.WindType} accentColor={ACCENT} />
            </p>

            <div className={s.typeBar}>
              {WIND_TYPES.map(t => (
                <button
                  key={t.value}
                  type="button"
                  className={`${s.typeBtn} ${p.WindType === t.value ? s.typeBtnActive : ""}`}
                  onClick={() => setP(prev => ({ ...prev, WindType: t.value }))}
                >
                  {t.label}
                </button>
              ))}
            </div>
            <p className={s.typeDesc}>{wt?.desc}</p>

            {/* ── Steady params ──────────────────────────────────────────── */}
            {p.WindType === 1 && (
              <div className={s.grid2} style={{ marginTop: 14 }}>
                <label className={s.field}>
                  <span className={s.fieldLabel}><Lbl k="HWindSpeed">Wind speed</Lbl></span>
                  <div className={s.inputRow}>
                    <input className={s.inp} type="number" value={p.HWindSpeed} onChange={setNum("HWindSpeed")} step="0.5" />
                    <span className={s.unit}>m/s</span>
                  </div>
                </label>
                <label className={s.field}>
                  <span className={s.fieldLabel}><Lbl k="RefHt">Reference height</Lbl></span>
                  <div className={s.inputRow}>
                    <input className={s.inp} type="number" value={p.RefHt} onChange={setNum("RefHt")} />
                    <span className={s.unit}>m</span>
                  </div>
                </label>
                <label className={s.field}>
                  <span className={s.fieldLabel}><Lbl k="PLexp">Power law exponent α</Lbl></span>
                  <input className={s.inp} type="number" value={p.PLexp} onChange={setNum("PLexp")} step="0.01" />
                </label>
              </div>
            )}

            {/* ── Uniform wind params ────────────────────────────────────── */}
            {p.WindType === 2 && (
              <div style={{ marginTop: 14, marginBottom: 22 }}>
                <label className={s.field}>
                  <span className={s.fieldLabel}><Lbl k="Filename_Uni">Wind file (.wnd)</Lbl></span>
                  <div className={s.fileRow}>
                    <input className={s.inp} type="text" value={p.Filename_Uni === "none" ? "" : p.Filename_Uni}
                      onChange={e => setP(prev => ({ ...prev, Filename_Uni: e.target.value || "none" }))}
                      placeholder="Path to .wnd file…" />
                    <button className={s.browseBtn} onClick={browseWnd} title="Browse" type="button">
                      <FolderOpen size={13} strokeWidth={1.8} />
                    </button>
                  </div>
                </label>
                <div className={s.grid2} style={{ marginTop: 12 }}>
                  <label className={s.field}>
                    <span className={s.fieldLabel}><Lbl k="RefHt_Uni">Reference height</Lbl></span>
                    <div className={s.inputRow}>
                      <input className={s.inp} type="number" value={p.RefHt_Uni} onChange={setNum("RefHt_Uni")} />
                      <span className={s.unit}>m</span>
                    </div>
                  </label>
                  <label className={s.field}>
                    <span className={s.fieldLabel}><Lbl k="RefLength">Reference length</Lbl></span>
                    <div className={s.inputRow}>
                      <input className={s.inp} type="number" value={p.RefLength} onChange={setNum("RefLength")} />
                      <span className={s.unit}>m</span>
                    </div>
                  </label>
                </div>
              </div>
            )}

            {/* ── TurbSim BTS params ─────────────────────────────────────── */}
            {p.WindType === 3 && (
              <div style={{ marginTop: 14, marginBottom: 22 }}>
                <label className={s.field}>
                  <span className={s.fieldLabel}><Lbl k="FileName_BTS">Wind field file (.bts)</Lbl></span>
                  <div className={s.fileRow}>
                    <input className={s.inp} type="text" value={p.FileName_BTS}
                      onChange={set("FileName_BTS")} placeholder="Path to .bts file…" />
                    <button className={s.browseBtn} onClick={browseBts} title="Browse" type="button">
                      <FolderOpen size={13} strokeWidth={1.8} />
                    </button>
                  </div>
                </label>

                {project && (
                  <div className={s.scanRow}>
                    <button className={s.scanBtn} onClick={scanBts} disabled={scanning} type="button">
                      <RefreshCw size={11} strokeWidth={2} className={scanning ? s.spinning : ""} />
                      {scanning ? "Scanning…" : "Scan project"}
                    </button>
                    {btsFiles.length > 0 ? (
                      <div className={s.btsPickerWrap}>
                        <select className={s.btsPicker} value={p.FileName_BTS}
                          onChange={e => e.target.value && setP(prev => ({ ...prev, FileName_BTS: e.target.value }))}>
                          <option value="">— {btsFiles.length} .bts files found —</option>
                          {btsFiles.map(f => (
                            <option key={f.path} value={f.path}>{f.rel}</option>
                          ))}
                        </select>
                        <ChevronDown size={12} className={s.btsChevron} />
                      </div>
                    ) : !scanning && (
                      <span className={s.noBts}>No .bts files — run TurbSim or DLC Batch first</span>
                    )}
                  </div>
                )}
              </div>
            )}

            {/* Flow Direction */}
            <p className={s.sectionHead} style={{ marginTop: p.WindType === 1 ? 0 : 4 }}>
              Flow Direction
            </p>
            <div className={s.grid2}>
              <label className={s.field}>
                <span className={s.fieldLabel}><Lbl k="PropagationDir">Propagation direction</Lbl></span>
                <div className={s.inputRow}>
                  <input className={s.inp} type="number" value={p.PropagationDir} onChange={setNum("PropagationDir")} step="1" />
                  <span className={s.unit}>°</span>
                </div>
                <span className={s.hint}>Met. convention — 0° = wind from North</span>
              </label>
              <label className={s.field}>
                <span className={s.fieldLabel}><Lbl k="VFlowAng">Upflow angle</Lbl></span>
                <div className={s.inputRow}>
                  <input className={s.inp} type="number" value={p.VFlowAng} onChange={setNum("VFlowAng")} step="0.5" />
                  <span className={s.unit}>°</span>
                </div>
                <span className={s.hint}>Vertical flow inclination</span>
              </label>
            </div>

            {/* Velocity Output Point */}
            <p className={s.sectionHead}>Velocity Output Point</p>
            <div className={s.grid2}>
              <label className={s.field}>
                <span className={s.fieldLabel}><Lbl k="WindVziList">Hub height (Z)</Lbl></span>
                <div className={s.inputRow}>
                  <input className={s.inp} type="number" value={p.WindVziList} onChange={setNum("WindVziList")} />
                  <span className={s.unit}>m</span>
                </div>
                <span className={s.hint}>Match ElastoDyn HubHt</span>
              </label>
              <div className={s.field}>
                <span className={s.fieldLabel}><Lbl k="SumPrint">Summary file</Lbl></span>
                <Toggle
                  value={p.SumPrint}
                  onChange={v => setP(prev => ({ ...prev, SumPrint: v }))}
                  label="Write .IfW.sum"
                />
              </div>
            </div>

            {/* ── Create new file — only shown when no file is currently loaded ── */}
            {!filePath && (
              <>
                <p className={s.sectionHead}>Create file</p>
                <div className={s.outputRow}>
                  <div className={s.autoNameBox}>
                    <span className={s.autoNameLabel}>Auto-name</span>
                    <span className={s.autoNameVal}>{autoName}</span>
                  </div>
                  <label className={s.field} style={{ marginTop: 8 }}>
                    <span className={s.fieldLabel}>
                      Custom filename <span className={s.unit}>(optional override)</span>
                    </span>
                    <input
                      className={s.inp}
                      type="text"
                      value={customDatName}
                      placeholder={autoName}
                      onChange={e => setCustomDatName(e.target.value)}
                    />
                  </label>
                  {project && (
                    <span className={s.hint} style={{ marginTop: 4 }}>
                      → {project.modelDir ?? project.workingDir}/{effectiveDatName}
                    </span>
                  )}
                </div>
                <div className={s.actionRow}>
                  <button
                    className={s.writeBtn}
                    onClick={handleGenerate}
                    disabled={generating || !project}
                    title={!project ? "Select a project folder first" : undefined}
                    type="button"
                  >
                    {generating ? "Writing…" : `Generate ${effectiveDatName}`}
                  </button>
                </div>
              </>
            )}


          </div>
        </div>

        {/* ── Stats sidebar ──────────────────────────────────────────────── */}
        <div className={s.statsPanel}>
          <span className={s.statsLabel}>Quick stats</span>
          <div className={s.turbineWrap}>
            <WindVizSVG windType={p.WindType} windSpeed={p.HWindSpeed} plExp={p.PLexp} />
          </div>
          <div className={s.statsGrid}>
            {stats.map(({ k, v }) => (
              <div key={k} className={s.statCard}>
                <span className={s.statKey}>{k}</span>
                <span className={s.statVal}>{v}</span>
              </div>
            ))}
          </div>
        </div>

      </div>
    </div>
  );
}
