// ── Auto-name helper ──────────────────────────────────────────────────────────
function autoFilename(windType, p) {
  if (windType === 1) {
    const v = String(Number(p.HWindSpeed).toFixed(1)).replace(".", "p");
    return `IFW_Steady_V${v}.dat`;
  }
  if (windType === 2 && p.Filename_Uni.trim() && p.Filename_Uni !== "none") {
    const base = p.Filename_Uni.trim().split(/[\\/]/).pop().replace(/\.wnd$/i, "");
    return `IFW_Uni_${base}.dat`;
  }
  if (windType === 3 && p.FileName_BTS.trim()) {
    const base = p.FileName_BTS.trim().split(/[\\/]/).pop().replace(/\.bts$/i, "");
    return `IFW_${base}.dat`;
  }
  return "InflowWind.dat";
}

