// ── Wind visualisation SVG ─────────────────────────────────────────────────────
// Shows a turbine (right) + horizontal shear arrows (left) — longer at top.
// For Steady: lengths follow a rough power-law gradient.
// For BTS: same arrows but slightly irregular to hint at turbulence.
function WindVizSVG({ windType, windSpeed, plExp }) {
  const c = "#378ADD";

  // [svgY, relativeLen] pairs — top to bottom = high altitude to low altitude
  const arrowRows = [
    [16, 1.00],
    [29, 0.83],
    [42, 0.67],
    [55, 0.52],
    [68, 0.39],
  ];
  const MAX_LEN = 24;

  return (
    <svg viewBox="0 0 100 110" width="100%" height="180" style={{ display: "block" }}>
      {/* Tower */}
      <line x1="68" y1="54" x2="68" y2="100"
        style={{ stroke: "var(--tx-4)" }} strokeWidth="5" strokeLinecap="round"/>
      {/* Base */}
      <line x1="56" y1="101" x2="80" y2="101"
        style={{ stroke: "var(--bd-strong)" }} strokeWidth="2"/>
      {/* Nacelle */}
      <rect x="60" y="48" width="16" height="8" rx="2"
        style={{ fill: "var(--bg-hover-md)" }}/>
      {/* Hub */}
      <circle cx="68" cy="52" r="3.5" fill={c}/>
      {/* Blades — up, lower-left, lower-right */}
      <line x1="68" y1="48" x2="68" y2="14"  stroke={c} strokeWidth="2.5" strokeLinecap="round"/>
      <line x1="65" y1="55" x2="42" y2="68"  stroke={c} strokeWidth="2.5" strokeLinecap="round"/>
      <line x1="71" y1="55" x2="94" y2="68"  stroke={c} strokeWidth="2.5" strokeLinecap="round"/>

      {/* Shear arrows */}
      {arrowRows.map(([y, rel], i) => {
        const len = MAX_LEN * rel;
        // For BTS: slight vertical wobble to hint at turbulence
        const dy  = windType === 3 ? ((i * 7) % 5) - 2 : 0;
        return (
          <g key={y} opacity="0.62">
            <line x1="4" y1={y + dy} x2={4 + len} y2={y + dy}
              stroke={c} strokeWidth="1.4" strokeLinecap="round"/>
            <polyline
              points={`${4 + len - 5},${y + dy - 3.5} ${4 + len},${y + dy} ${4 + len - 5},${y + dy + 3.5}`}
              stroke={c} strokeWidth="1.4" fill="none" strokeLinecap="round" strokeLinejoin="round"/>
          </g>
        );
      })}

      {/* Module label */}
      <text x="4" y="108" fontSize="6"
        style={{ fill: c }} fontFamily="-apple-system,sans-serif" opacity="0.7">
        {windType === 1
          ? `Steady  ${Number(windSpeed || 0).toFixed(1)} m/s  α=${plExp}`
          : windType === 2
          ? "Uniform (.wnd)"
          : windType === 3
          ? "TurbSim BTS"
          : "InflowWind"}
      </text>
    </svg>
  );
}

