// ── Parser ────────────────────────────────────────────────────────────────────
function parseInflowWindFile(content) {
  const kv = {};
  for (const raw of content.split("\n")) {
    const line = raw.trim();
    if (!line) continue;
    // Skip pure comment / separator / section-header lines
    if (line.startsWith("!") || line.startsWith("=") || /^-{3,}/.test(line)) continue;

    let rest = line;
    let value;

    // Quoted string value
    if (rest.startsWith('"')) {
      const end = rest.indexOf('"', 1);
      if (end === -1) continue;
      value = rest.slice(0, end + 1);
      rest  = rest.slice(end + 1).trim();
    } else {
      // Unquoted: grab up to first whitespace or comma
      const sp = rest.search(/[\s,]/);
      if (sp === -1) continue;
      value = rest.slice(0, sp);
      rest  = rest.slice(sp).trim();
    }

    // Key = next alpha token
    const m = rest.match(/^([A-Za-z_][A-Za-z0-9_]*)/);
    if (!m) continue;
    kv[m[1]] = value;
  }
  return kv;
}

